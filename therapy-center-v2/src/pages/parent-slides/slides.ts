// ─────────────────────────────────────────────────────────────
// ABA guide — slide data (declarative & modular).
//
// Standalone deck. Edit content here; ParentSlides.tsx renders each
// block. Inline emphasis is written with **double asterisks** → bold.
//
// Slide variants:
//   cover / closing → logo + title + sub
//   section         → full-screen section headline (divider)
//   content         → kick + title + blocks[]
// ─────────────────────────────────────────────────────────────

export type Block =
  | { type: 'lead'; text: string }
  | { type: 'bullets'; items: string[] }
  | { type: 'steps'; items: string[] }
  | { type: 'chips'; items: { label: string; sub?: string; icon?: string }[] }
  | { type: 'abc'; items: { lab: string; big: string; ex: string }[] }
  | { type: 'compare'; cards: { tag: string; title: string; text: string }[] }
  | { type: 'matrix'; groups: { head: string; tone: 'up' | 'down'; note?: string; rows: { name: string; kinds?: string }[] }[] }
  | { type: 'table'; cols: string[]; rows: string[][] }
  | { type: 'ladder'; items: { label: string; ex?: string; important?: boolean }[] }
  | { type: 'charts' }
  | { type: 'pull'; text: string };

export interface ContentSlide {
  variant: 'content';
  section: string;
  kick?: string;
  title: string;
  center?: boolean;
  art?: 'target';
  blocks: Block[];
}

export interface CoverSlide {
  variant: 'cover' | 'closing';
  section: string;
  eng?: string;
  title: string;
  sub?: string;
}

export interface SectionSlide {
  variant: 'section';
  section: string;
  title: string;
  sub?: string;
}

export type Slide = ContentSlide | CoverSlide | SectionSlide;

