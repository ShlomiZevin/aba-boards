// Default Hebrew text for the treatment agreement.
//
// The professional party is a single behaviour analyst, not an organisation:
// there is no "centre" and no staff. Therapists around the child belong to the
// child's environment, not to the analyst, so the document never presents them
// as her team or makes her answerable for them.
//
// This is the starting point the analyst edits before sending it out. It is
// filled from details already on record, so in the common case nothing has to
// be typed at all.
//
// The termination clause is the reason this document exists: either side may
// end the treatment, but only on written notice, so neither the analyst nor
// the family is left with an unmanaged ending.
//
// The wording is a general-purpose Israeli service agreement - a sensible
// default, not legal advice.

export interface AgreementTemplateInput {
  childName: string;
  parentNames: string[];
  analystName: string;
  analystRole: string;
  analystContact?: string;
  startDate?: string | null;
  noticeWeeks: number;
}

const BLANK = '______________';

function formatHebrewDate(iso?: string | null): string {
  if (!iso) return BLANK;
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return BLANK;
  return d.toLocaleDateString('he-IL', { day: '2-digit', month: '2-digit', year: 'numeric' });
}

/**
 * A start date already past reads "החל ביום", one still ahead reads "יחל ביום" — an
 * agreement is often signed after the work has started. With no date set we
 * assume it is still ahead.
 */
function startVerb(iso?: string | null): string {
  if (!iso) return 'יחל ביום';
  const start = new Date(iso);
  if (Number.isNaN(start.getTime())) return 'יחל ביום';
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  start.setHours(0, 0, 0, 0);
  return start < today ? 'החל ביום' : 'יחל ביום';
}

